"""
NUNO Training Script for 2D Darcy Flow (Live Sampling Version)
--------------------------------------------------------------
Updated training script that loads uniform grid data and samples it 
on-the-fly, replacing the static point cloud loading of the old script.
"""

import os
import glob
import h5py
from math import ceil

import hydra
from omegaconf import DictConfig
import torch
from torch.nn import MSELoss
from torch.optim import Adam, lr_scheduler
from torch.utils.data import Dataset, DataLoader

# PhysicsNeMo imports
from physicsnemo.distributed import DistributedManager
from physicsnemo.utils import StaticCaptureTraining, StaticCaptureEvaluateNoGrad
from physicsnemo.launch.utils import load_checkpoint, save_checkpoint
from physicsnemo.launch.logging import PythonLogger, LaunchLogger

# Local imports
from physicsnemo.models.fno.nuno import NUNO
from nuno_validator import NUNOValidator
from point_sampler import get_sampler  # Assumes point_sampler.py exists


class GridDarcyDataset(Dataset):
    """
    Dataset to load uniform grid Darcy data from HDF5 shards.
    Expects data generated by generate_darcy_grids.py (already normalized).
    """
    def __init__(self, data_dir: str, split: str):
        self.data_dir = data_dir
        self.split = split
        
        split_path = os.path.join(self.data_dir, self.split)
        self.file_paths = sorted(glob.glob(os.path.join(split_path, "*.h5")))
        
        if not self.file_paths:
            raise FileNotFoundError(f"No HDF5 files found in {split_path}")

        self.num_samples_per_file = []
        self.file_cumulative_samples = [0]
        
        # Scan files to build index
        for file_path in self.file_paths:
            with h5py.File(file_path, 'r') as f:
                num_in_file = f['permeability'].shape[0]
                self.num_samples_per_file.append(num_in_file)
                self.file_cumulative_samples.append(self.file_cumulative_samples[-1] + num_in_file)

        self.total_samples = self.file_cumulative_samples[-1]

    def __len__(self):
        return self.total_samples

    def __getitem__(self, index):
        # Locate file and local index
        file_idx = next(i for i, total in enumerate(self.file_cumulative_samples) if total > index) - 1
        local_idx = index - self.file_cumulative_samples[file_idx]
        
        with h5py.File(self.file_paths[file_idx], 'r') as f:
            # Load data: (H, W, C) -> (C, H, W)
            # Note: Data is assumed to be PRE-NORMALIZED by the generator
            permeability = torch.from_numpy(f['permeability'][local_idx]).permute(2, 0, 1)
            pressure = torch.from_numpy(f['pressure'][local_idx]).permute(2, 0, 1)

        return {'permeability': permeability, 'pressure': pressure}


@hydra.main(version_base="1.3", config_path=".", config_name="nuno_config")
def nuno_trainer(cfg: DictConfig) -> None:
    """
    Training for NUNO on 2D Darcy flow with live sampling.
    """
    # Initialize distributed manager
    DistributedManager.initialize()
    dist = DistributedManager()
    
    # Initialize logging
    log = PythonLogger(name="nuno_darcy")
    log.file_logging()
    LaunchLogger.initialize()
    
    log.info("=" * 60)
    log.info("NUNO Training: Live Sampling from Uniform Grids")
    log.info("=" * 60)
    
    # Setup normalization constants (FOR VALIDATION ONLY)
    # We assume input data is already normalized by the generator.
    norm_vars = cfg.normalizer
    normalizer = {
        'permeability': (norm_vars.permeability.mean, norm_vars.permeability.std_dev),
        'darcy': (norm_vars.darcy.mean, norm_vars.darcy.std_dev)
    }
    
    # -----------------------------------------------------------------------
    # 1. Setup Sampler
    # -----------------------------------------------------------------------
    log.info(f"Initializing sampler: {cfg.sampler.name}")
    # This generates the fixed coordinates for this run
    sampler = get_sampler(cfg, dist.device)
    coordinates = sampler.coordinates
    log.info(f"Point cloud geometry: {sampler.num_points} points")

    # -----------------------------------------------------------------------
    # 2. Create Dataloaders (Grid Data)
    # -----------------------------------------------------------------------
    log.info("Loading training grids...")
    train_dataset = GridDarcyDataset(data_dir=cfg.data.data_dir, split="train")
    train_loader = DataLoader(
        train_dataset,
        batch_size=cfg.training.batch_size,
        shuffle=True,
        num_workers=cfg.data.num_workers,
        pin_memory=True
    )
    
    log.info("Loading validation grids...")
    val_dataset = GridDarcyDataset(data_dir=cfg.data.data_dir, split="val")
    val_loader = DataLoader(
        val_dataset,
        batch_size=cfg.training.batch_size,
        shuffle=False,
        num_workers=cfg.data.num_workers,
        drop_last=False 
    )

    # -----------------------------------------------------------------------
    # 3. Create Model
    # -----------------------------------------------------------------------
    log.info("Creating NUNO model...")

    model = NUNO(
        coordinates=coordinates.cpu().numpy(),
        in_channels=cfg.arch.nuno.in_channels,
        out_channels=cfg.arch.nuno.dimension,
        n_subdomains=cfg.arch.nuno.n_subdomains,
        modes=12,
        width=32,
        num_layers=4,
    )
    
    # Setup domain decomposition with the sampler's fixed coordinates
    # log.info("Setting up domain decomposition...")

    # model.setup_domain(coordinates)

    model = model.to(dist.device)
    
    # Log model info
    n_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    log.info(f"Model parameters: {n_params:,}")
    log.info(f"Subdomains: {model.n_subdomains}")
    
    # -----------------------------------------------------------------------
    # 4. Training Components
    # -----------------------------------------------------------------------
    loss_fun = MSELoss(reduction="mean")
    optimizer = Adam(model.parameters(), lr=cfg.scheduler.initial_lr)
    scheduler = lr_scheduler.LambdaLR(
        optimizer, 
        lr_lambda=lambda step: cfg.scheduler.decay_rate ** step
    )
    
    # Validator gets the normalizer to denormalize for plotting/metrics
    validator = NUNOValidator(
        loss_fun=MSELoss(reduction="mean"),
        norm=normalizer,
        use_triangulation=cfg.validation.use_triangulation
    )
    
    # Checkpoint setup
    ckpt_args = {
        "path": "./checkpoints",
        "optimizer": optimizer,
        "scheduler": scheduler,
        "models": model,
    }
    # loaded_pseudo_epoch = load_checkpoint(device=dist.device, **ckpt_args)
    loaded_pseudo_epoch = 0
    
    steps_per_pseudo_epoch = ceil(
        cfg.training.pseudo_epoch_sample_size / cfg.training.batch_size
    )
    
    log_args = {
        "name_space": "train",
        "num_mini_batch": steps_per_pseudo_epoch,
        "epoch_alert_freq": 1,
    }
    
    # Define forward passes
    @StaticCaptureTraining(
        model=model, optim=optimizer, logger=log, use_amp=False, use_graphs=False
    )
    def forward_train(invars, target):
        """Training forward pass."""
        pred = model(invars)
        loss = loss_fun(pred, target)
        return loss
    
    @StaticCaptureEvaluateNoGrad(
        model=model, logger=log, use_amp=False, use_graphs=False
    )
    def forward_eval(invars):
        """Evaluation forward pass."""
        return model(invars)
    
    # -----------------------------------------------------------------------
    # 5. Training Loop
    # -----------------------------------------------------------------------
    if loaded_pseudo_epoch == 0:
        log.success("Training started...")
    else:
        log.warning(f"Resuming training from pseudo epoch {loaded_pseudo_epoch + 1}.")
    
    for pseudo_epoch in range(
        max(1, loaded_pseudo_epoch + 1), cfg.training.max_pseudo_epochs + 1
    ):
        # Training phase
        model.train()
        with LaunchLogger(**log_args, epoch=pseudo_epoch) as logger:
            train_iter = iter(train_loader)
            for step in range(steps_per_pseudo_epoch):
                try:
                    batch = next(train_iter)
                except StopIteration:
                    train_iter = iter(train_loader)
                    batch = next(train_iter)
                
                # 1. Move Grid to Device
                grid_k = batch['permeability'].to(dist.device) # (B, 1, H, W)
                grid_p = batch['pressure'].to(dist.device)     # (B, 1, H, W)
                
                # 2. Live Sampling (Interpolation)
                # Note: We rely on the generator having already normalized the grid data.
                # We do NOT subtract batch means here (fixing the inconsistency).
                invar = sampler.sample(grid_k)  # (B, N, 1)
                target = sampler.sample(grid_p) # (B, N, 1)
                
                # 3. Forward Pass
                loss = forward_train(invar, target)
                logger.log_minibatch({"loss": loss.detach()})
            
            logger.log_epoch({"Learning Rate": optimizer.param_groups[0]["lr"]})
        
        # Save checkpoint
        if pseudo_epoch % cfg.training.rec_results_freq == 0:
            save_checkpoint(**ckpt_args, epoch=pseudo_epoch)
            log.info(f"Saved checkpoint at epoch {pseudo_epoch}")
        
        # Validation phase
        if pseudo_epoch % cfg.validation.validation_pseudo_epochs == 0:
            model.eval()
            with LaunchLogger("valid", epoch=pseudo_epoch) as logger:
                total_loss = 0.0
                num_val_batches = 0
                
                for val_step, batch in enumerate(val_loader):
                    grid_k = batch['permeability'].to(dist.device)
                    grid_p = batch['pressure'].to(dist.device)
                    
                    # Sample validation data
                    invar = sampler.sample(grid_k)
                    target = sampler.sample(grid_p)
                    
                    # Forward pass
                    prediction = forward_eval(invar)

                    # Validate (with visualization on first batch)
                    if val_step == 0:
                        # Validator will denormalize using 'normalizer' stats for plotting
                        val_loss = validator.compare(
                            coordinates, invar, target, prediction,
                            pseudo_epoch, logger
                        )
                    else:
                        val_loss = loss_fun(prediction, target).item()
                    
                    total_loss += val_loss
                    num_val_batches += 1
                
                avg_val_loss = total_loss / max(num_val_batches, 1)
                logger.log_epoch({"Validation error": avg_val_loss})
                log.info(f"Epoch {pseudo_epoch}: Validation loss = {avg_val_loss:.6f}")
                    
        # Update learning rate
        if pseudo_epoch % cfg.scheduler.decay_pseudo_epochs == 0:
            scheduler.step()
            log.info(f"Learning rate decayed to {optimizer.param_groups[0]['lr']:.2e}")
    
    # Final checkpoint
    save_checkpoint(**ckpt_args, epoch=cfg.training.max_pseudo_epochs)
    log.success("Training completed!")

if __name__ == "__main__":
    nuno_trainer()